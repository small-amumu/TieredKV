def strip29(name):
    """(core, (lag, C, b, order, fallback)) for a sel29 name, else (name, None)."""
    m = SUF29.fullmatch(name) if name else None
    if not m:
        n_ = SUF30N.fullmatch(name) if name else None
        if n_ and not BAD30.fullmatch(n_[1]):
            return n_[1], (1, 0, 0, "n", "k")                    # _nh0: order "n" = no host rows
        if name and BAD30.fullmatch(name):
            raise ValueError(f"{name}: malformed VFB suffix (_vf<lag>c<C>b<b><o><f> or _nh0, once)")
        return name, None
    if int(m[2]) > MAXLAG or BAD30.fullmatch(m[1]):
        raise ValueError(f"{name}: malformed VFB suffix (lag 1 - {MAXLAG}, one suffix)")
    return m[1], (int(m[2]), int(m[3]), int(m[4]), m[5], m[6])


P30 = re.compile(r".+_p[1-9]\d*_h[2-8f][2-8f]")


def _lam30(c):
    """True for a plain sel14 _h name with a _p<L> correction (lam < 0; in sel13_q's grammar _p<L> is the last
    token of the base name). Decided on the text, so names of other grammars are passed on untouched."""
    return bool(c) and P30.fullmatch(c) is not None


def _check30(c):
    """a vf / nh core must be a plain sel14 _h name with x2s<M>, K > 0 and lam <= 0 (plain or _p<L>)."""
    s_ = Q14.split(c) if c else None
    if s_ is None or s_[3]:
        raise ValueError(f"{c}: VFB suffixes need a plain sel14 _h<rk><rv> name")
    p = Q14.parse(c)
    if p["lam"] > 0 or p.get("jcal") or p.get("mass") or p["eb"] or p["tw"] or p["crit"][:2] != "2s" or not p["K"]:
        raise ValueError(f"{c}: VFB needs an x2s<M> criterion with K > 0 and lam <= 0 (plain or _p<L>)")
    return c


def alias(name):
    c, p = strip29(name)
    if not p:
        return Q28.alias(name)
    return c if _lam30(c) else f"{c}_r0"


def _b30(name):
    """the sel14_q name of a configuration-B name: the core of a vf / nh name whose core has lam < 0 (checked by
    _check30), or a plain _p<L> _h name with no sel19 - sel28 suffix; None for every other name."""
    if not name:
        return None
    c, p = strip29(name)
    if p:
        return _check30(c) if _lam30(c) else None
    return name if _lam30(name) and Q28.strip19(name)[1] is None else None


